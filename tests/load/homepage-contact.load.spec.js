// US-029: exactly 5 concurrent users load the homepage and contact page.
//
// HARD CONSTRAINT (brief, stated 3×): never more than 5 concurrent users.
//  - USERS is checked against MAX_CONCURRENT_USERS before anything starts.
//  - The `load` project runs with workers: 1, retries: 0, and as a teardown project
//    (after every other suite finishes), so no other test traffic overlaps it.
//  - A live in-flight counter proves the peak concurrency in the report.
import { test, expect } from '@playwright/test';
import { MAX_CONCURRENT_USERS, LOAD_P95_BUDGET_MS, SITE } from '../../utils/test-data.js';
import { summarize, writeDoc } from '../../utils/helpers.js';

const USERS = 5;
const ITERATIONS = 3;
const JOURNEY = ['/', '/contact'];
const NAV_TIMEOUT_MS = 30_000;

test.describe.configure({ mode: 'serial', retries: 0 });

test('US-029: 5 concurrent users, p95 < 3 s, zero 5xx @P0 @load', async ({ browser }, testInfo) => {
  test.setTimeout(15 * 60_000);

  // ---- guard: refuse to run if the user count was ever raised ----
  expect(USERS, `brief limit is ${MAX_CONCURRENT_USERS} concurrent users`).toBeLessThanOrEqual(MAX_CONCURRENT_USERS);
  expect(testInfo.config.workers, 'load must not run alongside other workers').toBeGreaterThanOrEqual(1);

  const samples = []; // one row per document navigation
  const serverErrors = []; // any 5xx on techdome.io (documents + assets)
  let inFlight = 0;
  let peak = 0;
  const startedAt = new Date();

  const contexts = await Promise.all(Array.from({ length: USERS }, () => browser.newContext()));

  async function runUser(ctx, user) {
    const page = await ctx.newPage();
    // Don't inflate Techdome's analytics/ad numbers with synthetic traffic.
    await page.route(url => !url.hostname.endsWith('techdome.io'), r => r.abort());
    page.on('response', r => {
      if (r.status() >= 500 && new URL(r.url()).hostname.endsWith('techdome.io')) {
        serverErrors.push({ user, status: r.status(), url: r.url() });
      }
    });

    inFlight++;
    peak = Math.max(peak, inFlight);
    try {
      for (let i = 1; i <= ITERATIONS; i++) {
        for (const path of JOURNEY) {
          const t0 = Date.now();
          const row = { user, iteration: i, path };
          try {
            const res = await page.goto(path, { waitUntil: 'domcontentloaded', timeout: NAV_TIMEOUT_MS });
            const timing = res.request().timing();
            row.status = res.status();
            row.ttfbMs = Math.round(timing.responseStart);
            row.responseMs = Math.round(timing.responseEnd); // full HTML document received
            row.domContentLoadedMs = Date.now() - t0;
            row.cache = `${res.headers()['cf-cache-status'] ?? '-'}/${res.headers()['x-nextjs-cache'] ?? '-'}`;
          } catch (e) {
            row.status = 0;
            row.error = e.message.split('\n')[0];
            row.responseMs = NAV_TIMEOUT_MS; // count a timeout as the worst case, not as "missing"
            row.domContentLoadedMs = Date.now() - t0;
          }
          samples.push(row);
        }
      }
    } finally {
      inFlight--;
    }
  }

  // All 5 users start together and run concurrently.
  await Promise.all(contexts.map((ctx, i) => runUser(ctx, i + 1)));
  await Promise.all(contexts.map(c => c.close()));
  const finishedAt = new Date();

  // ---- analysis ----
  const response = summarize(samples.map(s => s.responseMs));
  const ttfb = summarize(samples.filter(s => s.ttfbMs !== undefined).map(s => s.ttfbMs));
  const dcl = summarize(samples.map(s => s.domContentLoadedMs));
  const perPath = Object.fromEntries(JOURNEY.map(p => [p, summarize(samples.filter(s => s.path === p).map(s => s.responseMs))]));
  const failed = samples.filter(s => s.status === 0 || s.status >= 400);
  const verdict = {
    concurrency: peak === USERS && peak <= MAX_CONCURRENT_USERS,
    p95: response.p95 < LOAD_P95_BUDGET_MS,
    no5xx: serverErrors.length === 0,
  };
  const pass = Object.values(verdict).every(Boolean);

  const md = `# Load Test Results: US-029

> Generated by \`tests/load/homepage-contact.load.spec.js\` on ${finishedAt.toISOString()}.
> Re-running \`npx playwright test\` (or \`npm run test:load\`) overwrites this file.

## Verdict: ${pass ? '✅ PASS' : '❌ FAIL'}

| Criterion | Target | Measured | Result |
|---|---|---|---|
| Concurrent users (peak) | exactly ${USERS}, never > ${MAX_CONCURRENT_USERS} | **${peak}** | ${verdict.concurrency ? '✅' : '❌'} |
| p95 document response time | < ${LOAD_P95_BUDGET_MS} ms | **${response.p95} ms** | ${verdict.p95 ? '✅' : '❌'} |
| HTTP 5xx responses (documents + assets) | 0 | **${serverErrors.length}** | ${verdict.no5xx ? '✅' : '❌'} |

## Setup
- Target: ${SITE.origin}. Journey per user: ${JOURNEY.map(p => `\`${p}\``).join(' → ')}, repeated ${ITERATIONS}× (${samples.length} document requests in total)
- ${USERS} isolated browser contexts (Chromium, fresh cache/cookies each) started simultaneously in **one** worker
- The \`load\` project runs after all other suites (teardown project), with \`workers: 1\` and \`retries: 0\`, so no other test traffic overlaps
- Third-party requests (analytics/ads) blocked to avoid polluting Techdome's marketing data
- "Response time" = navigation start → last byte of the HTML document (\`responseEnd\`). Requests that time out (${NAV_TIMEOUT_MS / 1000} s) count as ${NAV_TIMEOUT_MS} ms
- Window: ${startedAt.toISOString()} → ${finishedAt.toISOString()} (${Math.round((finishedAt - startedAt) / 1000)} s)

## Summary (ms)
| Metric | n | min | p50 | p95 | max | avg |
|---|---|---|---|---|---|---|
| Document response (all) | ${response.count} | ${response.min} | ${response.p50} | **${response.p95}** | ${response.max} | ${response.avg} |
${JOURNEY.map(p => `| Document response \`${p}\` | ${perPath[p].count} | ${perPath[p].min} | ${perPath[p].p50} | ${perPath[p].p95} | ${perPath[p].max} | ${perPath[p].avg} |`).join('\n')}
| TTFB | ${ttfb.count} | ${ttfb.min} | ${ttfb.p50} | ${ttfb.p95} | ${ttfb.max} | ${ttfb.avg} |
| DOMContentLoaded (wall clock) | ${dcl.count} | ${dcl.min} | ${dcl.p50} | ${dcl.p95} | ${dcl.max} | ${dcl.avg} |

Failed / non-2xx document requests: **${failed.length}**${failed.length ? `\n\n${failed.map(f => `- user ${f.user} ${f.path} (iter ${f.iteration}): ${f.status || f.error}`).join('\n')}` : ''}

5xx responses: ${serverErrors.length ? `\n\n${serverErrors.map(e => `- user ${e.user}: ${e.status} ${e.url}`).join('\n')}` : 'none'}

## All samples
| User | Iter | Path | Status | TTFB | Response | DCL | Cache (CF / Next) |
|---|---|---|---|---|---|---|---|
${samples.map(s => `| ${s.user} | ${s.iteration} | \`${s.path}\` | ${s.status || 'ERR'} | ${s.ttfbMs ?? '-'} | ${s.responseMs} | ${s.domContentLoadedMs} | ${s.cache ?? s.error ?? '-'} |`).join('\n')}

## Interpretation
- Pages are pre-rendered by Next.js (\`x-nextjs-cache: HIT\`), but Cloudflare reports \`cf-cache-status: DYNAMIC\`, so every request still travels to the Railway origin. Response time therefore reflects origin and network latency, not just a CDN edge.
- 5 users is a very light load, so this is a sanity check that the site holds up under a handful of simultaneous visitors, not a capacity test. Exploration found 20 s TTFB spikes with even 1–3 requests (see \`docs/site-exploration.md\` §10), so a failing p95 here points to origin latency rather than saturation.
- Results vary run to run on a live site. Compare several runs before drawing conclusions.
`;
  writeDoc('load-test-results.md', md);
  await testInfo.attach('load-samples.json', { body: JSON.stringify({ peak, samples, serverErrors }, null, 2), contentType: 'application/json' });
  await testInfo.attach('load-test-results.md', { body: md, contentType: 'text/markdown' });

  // ---- assertions (after the report is written, so it exists even on failure) ----
  expect(peak, 'peak concurrent users').toBe(USERS);
  expect(peak).toBeLessThanOrEqual(MAX_CONCURRENT_USERS);
  expect(serverErrors, 'HTTP 5xx during the run').toEqual([]);
  expect(response.p95, `p95 document response time (budget ${LOAD_P95_BUDGET_MS} ms)`).toBeLessThan(LOAD_P95_BUDGET_MS);
});
